import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const scenes = JSON.parse(fs.readFileSync(path.join(root, 'content/narration-scenes.json'), 'utf8'));
const production = JSON.parse(fs.readFileSync(path.join(root, 'content/voice-production.json'), 'utf8'));
const ffprobe = path.join(root, 'node_modules/@remotion/compositor-darwin-arm64/ffprobe');
const fps = 30, leadFrames = 8, tailFrames = 20;
const keepScenes = process.argv.includes('--keep-scenes');
const previous = keepScenes ? JSON.parse(fs.readFileSync(path.join(root,'content/timeline.json'),'utf8')) : null;
let cursor = 0;
const timeline = production.scenes.map((clip) => {
  const scene = scenes.find((item) => item.id === clip.id);
  const info = JSON.parse(execFileSync(ffprobe, ['-v','error','-show_entries','format=duration','-of','json',path.join(root, 'public', clip.audio)], {encoding:'utf8', env: {...process.env, DYLD_LIBRARY_PATH:path.dirname(ffprobe)}}));
  const durationSeconds = Number(info.format.duration);
  const audioFrames = Math.ceil(durationSeconds * fps);
  const durationInFrames = previous?.scenes.find((item)=>item.id===clip.id)?.durationInFrames ?? audioFrames + leadFrames + tailFrames;
  if(audioFrames+leadFrames+2>durationInFrames) throw new Error(`${clip.id}: new speech exceeds the existing scene. Rebuild timing and render the video again.`);
  const entry = {...clip, narration: scene.narration, from: cursor, audioFrames, durationSeconds, durationInFrames};
  cursor += durationInFrames;
  return entry;
});
const lines = timeline.map((clip) => `  ${JSON.stringify(clip.id)}: {file: ${JSON.stringify(clip.audio)}, frames: ${clip.audioFrames}, sceneFrames: ${clip.durationInFrames}},`);
fs.writeFileSync(path.join(root, 'src/curriculum/audio-timing.ts'), `// Generated by scripts/build-timing.mjs from the actual audio files.\nimport type {SceneId} from './types';\n\nexport const AUDIO_CLIPS: Partial<Record<SceneId, {file: string; frames: number; sceneFrames?: number}>> = {\n${lines.join('\n')}\n};\n`);
fs.writeFileSync(path.join(root, 'content/timeline.json'), JSON.stringify({fps, leadFrames, tailFrames, totalFrames:cursor, durationSeconds:cursor/fps, scenes:timeline}, null, 2)+'\n');

const stamp = (seconds) => {
  const millis = Math.max(0, Math.round(seconds * 1000));
  return `${String(Math.floor(millis/3600000)).padStart(2,'0')}:${String(Math.floor(millis/60000)%60).padStart(2,'0')}:${String(Math.floor(millis/1000)%60).padStart(2,'0')},${String(millis%1000).padStart(3,'0')}`;
};
const captions = [];
for (const clip of timeline) {
  const raw = JSON.parse(fs.readFileSync(path.join(root, 'public', clip.alignment), 'utf8'));
  const alignment = raw.alignment ?? raw.normalized_alignment;
  const chars = alignment.characters;
  let start = 0;
  for(let i=0;i<chars.length;i++) {
    const size = i-start+1;
    const sentenceEnd = /[.!?]/.test(chars[i]);
    const softBreak = size >= 27 && /[ ,]/.test(chars[i]);
    if ((sentenceEnd && size >= 8) || softBreak || size >= 38 || i === chars.length-1) {
      const text = chars.slice(start,i+1).join('').trim();
      if(text) captions.push({start:(clip.from+leadFrames)/fps+alignment.character_start_times_seconds[start],end:(clip.from+leadFrames)/fps+alignment.character_end_times_seconds[i],text});
      start=i+1;
    }
  }
}
fs.mkdirSync(path.join(root, 'out'), {recursive:true});
fs.writeFileSync(path.join(root,'out/BiaDone-Edu-Curriculum.ko.srt'), captions.map((c,i)=>`${i+1}\n${stamp(c.start)} --> ${stamp(c.end)}\n${c.text}\n`).join('\n'));
console.log(JSON.stringify({scenes:timeline.length,totalFrames:cursor,durationSeconds:cursor/fps,audioSeconds:timeline.reduce((sum,c)=>sum+c.durationSeconds,0),captionCues:captions.length,sceneDurations:timeline.map(c=>({id:c.id,seconds:Math.round(c.durationInFrames/fps*10)/10}))},null,2));
