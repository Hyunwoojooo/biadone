#!/usr/bin/env node
// Codex version qualification data (audit CDX-7, 2026-11-13).
//
// One reviewed JSON file per supported Codex release lives in
// bridges/codex/qualification/<version>.json. Swift reads only the generated
// sources below, which are compiled into the signed app; nothing is loaded at
// runtime. Add a version with `register`, then run `generate`.
//
//   node scripts/codex/qualification.mjs generate   write the generated Swift
//   node scripts/codex/qualification.mjs check      fail if generated Swift is stale
//
// Registration of a new release is `scripts/codex/register-version.mjs`.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const QUALIFICATION_DIRECTORY = join(root, 'bridges/codex/qualification');
export const GENERATED_HOOK = join(root, 'bridges/codex/swift/core/HookPermissionProfiles.generated.swift');
export const GENERATED_RELEASES = join(root, 'bridges/codex/swift/setup/CodexQualificationData.generated.swift');
export const SCHEMA = 'blabee.codex-qualification.v1';
export const CAPABILITIES = ['managedAppServer', 'pluginCLI', 'serverOwnedWorkspaceRoots', 'updateLifecycle'];
const TARGETS = ['aarch64-apple-darwin'];
const HEADER = '// Generated by scripts/codex/qualification.mjs from bridges/codex/qualification/*.json.\n'
  + '// Do not edit. Change the JSON, then run `npm run codex:qualification -- generate`.\n';

export const compareVersions = (a, b) => {
  const [x, y] = [a, b].map(v => v.split('.').map(Number));
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i];
  return 0;
};

function fail(message) { throw new Error(message); }

/** Strict validation: unknown keys, versions, capabilities or digests fail. */
export function validateRecord(value, fileName) {
  const where = fileName ? `${fileName}: ` : '';
  const keys = ['schema', 'version', 'target', 'capabilities', 'hook_cdhash', 'catalog', 'notes'];
  if (!value || typeof value !== 'object' || Array.isArray(value)
      || Object.keys(value).sort().join() !== [...keys].sort().join()) fail(`${where}unexpected keys`);
  if (value.schema !== SCHEMA) fail(`${where}schema must be ${SCHEMA}`);
  if (!/^\d+\.\d+\.\d+$/.test(value.version)) fail(`${where}version must be an exact stable version`);
  if (fileName && fileName !== `${value.version}.json`) fail(`${where}file name must match version`);
  if (!TARGETS.includes(value.target)) fail(`${where}unsupported target`);
  if (!Array.isArray(value.capabilities) || value.capabilities.length === 0
      || new Set(value.capabilities).size !== value.capabilities.length
      || value.capabilities.some(c => !CAPABILITIES.includes(c))) fail(`${where}invalid capabilities`);
  if (value.hook_cdhash !== null && !/^[0-9a-f]{40}$/.test(value.hook_cdhash)) fail(`${where}hook_cdhash must be 40 hex or null`);
  if (value.catalog !== null) {
    const catalog = value.catalog;
    if (!catalog || Object.keys(catalog).sort().join() !== 'file_digests,fingerprint,signing_team') fail(`${where}invalid catalog`);
    if (!/^[A-Z0-9]{10}$/.test(catalog.signing_team)) fail(`${where}invalid signing_team`);
    if (!/^[0-9a-f]{64}$/.test(catalog.fingerprint)) fail(`${where}invalid fingerprint`);
    const files = Object.entries(catalog.file_digests ?? {});
    if (files.length === 0 || files.some(([path, digest]) => !/^[A-Za-z0-9._/-]+$/.test(path) || path.startsWith('/')
        || path.split('/').includes('..') || !/^[0-9a-f]{64}$/.test(digest))) fail(`${where}invalid file_digests`);
    if (!catalog.file_digests['bin/codex']) fail(`${where}catalog must include bin/codex`);
  }
  if (!Array.isArray(value.notes) || value.notes.some(n => typeof n !== 'string' || n.includes('\n'))) fail(`${where}invalid notes`);
  return value;
}

export async function loadRecords(directory = QUALIFICATION_DIRECTORY) {
  const names = (await readdir(directory)).filter(name => name.endsWith('.json'));
  const records = [];
  for (const name of names) records.push(validateRecord(JSON.parse(await readFile(join(directory, name), 'utf8')), name));
  return records.sort((a, b) => compareVersions(a.version, b.version));
}

const q = text => JSON.stringify(text);
const comments = (notes, indent) => notes.map(note => `${indent}// ${note}\n`).join('');

export function renderHookProfiles(records) {
  const rows = records.filter(r => r.hook_cdhash).map(r => `        .init(version: ${q(r.version)}, cdHash: ${q(r.hook_cdhash)}),\n`);
  return `${HEADER}\nextension HookPermissionPolicy {\n    /// Primary \`bin/codex\` CDHash per reviewed release. Auxiliary executables\n`
    + `    /// (for example \`codex-exec-server\`) are never Hook callers.\n`
    + `    static let generatedQualifiedProfiles: [RuntimeProfile] = [\n${rows.join('')}    ]\n}\n`;
}

export function renderReleases(records) {
  const rows = records.map(r => {
    const caps = CAPABILITIES.filter(c => r.capabilities.includes(c)).map(c => `.${c}`).join(', ');
    let catalog = 'nil';
    if (r.catalog) {
      const files = Object.keys(r.catalog.file_digests).sort()
        .map(path => `                    ${q(path)}:\n                        ${q(r.catalog.file_digests[path])},\n`).join('');
      catalog = `Catalog(\n                signingTeamIdentifier: ${q(r.catalog.signing_team)},\n                fileDigests: [\n${files}`
        + `                ],\n                fingerprint:\n                    ${q(r.catalog.fingerprint)}\n            )`;
    }
    return `${comments(r.notes, '        ')}        Release(\n            version: ${q(r.version)}, target: ${q(r.target)},\n`
      + `            capabilities: [${caps}],\n            catalog: ${catalog}\n        ),\n`;
  });
  return `${HEADER}\n/// Reviewed Codex releases. \`CodexCompatibility\` reads capabilities and\n`
    + '/// `ManagedCodexRuntimeBundleQualificationCatalog` reads catalogs from here.\n'
    + 'enum CodexQualificationData {\n'
    + '    struct Catalog: Sendable {\n        let signingTeamIdentifier: String\n        let fileDigests: [String: String]\n        let fingerprint: String\n    }\n\n'
    + '    struct Release: Sendable {\n        let version: String\n        let target: String\n'
    + '        let capabilities: Set<CodexCompatibility.CapabilityProfile>\n        let catalog: Catalog?\n    }\n\n'
    + `    static let releases: [Release] = [\n${rows.join('')}    ]\n}\n`;
}

export async function generated(directory = QUALIFICATION_DIRECTORY) {
  const records = await loadRecords(directory);
  return new Map([[GENERATED_HOOK, renderHookProfiles(records)], [GENERATED_RELEASES, renderReleases(records)]]);
}

export async function checkGenerated(directory = QUALIFICATION_DIRECTORY) {
  const stale = [];
  for (const [path, text] of await generated(directory)) {
    const current = await readFile(path, 'utf8').catch(() => null);
    if (current !== text) stale.push(path);
  }
  return stale;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const command = process.argv[2];
  try {
    if (command === 'generate') {
      for (const [path, text] of await generated()) await writeFile(path, text);
      console.log('Generated Codex qualification Swift sources.');
    } else if (command === 'check') {
      const stale = await checkGenerated();
      if (stale.length) fail(`Generated sources are stale: ${stale.join(', ')}. Run: npm run codex:qualification -- generate`);
      console.log('Generated Codex qualification Swift sources are current.');
    } else fail('usage: qualification.mjs generate|check');
  } catch (error) { console.error(`codex qualification: ${error.message}`); process.exitCode = 1; }
}
